"""Regression tests for the 2026-11-04 correction pass on the discarded
target-evidence audit.

These tests encode adjudicated propositions, not coder labels. They fail
against the pre-correction audit-final.json (kept in
target-audit/pre-correction-2026-11-04/) and must pass against outputs
regenerated by the corrected finalize_audit.py.

Run: python3 -m unittest analysis.tests.test_target_audit_finalize
or:  python3 analysis/tests/test_target_audit_finalize.py
"""
from __future__ import annotations

import json
import unittest
from pathlib import Path

BASE = Path(__file__).resolve().parents[1] / "matrix-lesion" / "target-audit"


def _final():
    return json.loads((BASE / "audit-final.json").read_text())


def _units(variant, prop):
    return _final()[variant]["unit_level"].get(prop, {})


class TestCorrectedUnits(unittest.TestCase):
    def test_no_event_multiplication_unit(self):
        for variant in ("including_pass_weak", "strict_pass_only"):
            self.assertFalse(
                any("event-multiplication" in u
                    for u in _units(variant, "P10")), variant)

    def test_no_adjacent_strengthening_support(self):
        # HUH is occurrence-only, OKAY pattern is unspecified, WOW token
        # is Stange's discarded whoa example. Nothing supports this unit.
        for variant in ("including_pass_weak", "strict_pass_only"):
            self.assertNotIn(
                "adjacent-repetition|strengthening -> ITEM-DIRECT",
                _units(variant, "P10"), variant)

    def test_wow_p10_is_silence_after_wrong_use_rejection(self):
        pairs = _final()["including_pass_weak"]["pair_level"]
        self.assertEqual(pairs["P10/WOW"], "SILENCE")
        self.assertEqual(pairs["P10/HUH"], "ITEM-DIRECT")
        self.assertEqual(pairs["P10/OKAY"], "ITEM-DIRECT")

    def test_potts_units_carry_mixed_positions(self):
        units = _units("including_pass_weak", "P10")
        self.assertEqual(
            units.get("distributed-recurrence[mixed]|strengthening"
                      " -> ITEM-DIRECT"), 2)
        self.assertEqual(
            units.get("distributed-recurrence[mixed]|redundancy"
                      " -> ITEM-DIRECT"), 2)

    def test_ouch_attempted_negation_single_host(self):
        # One Heine observation cannot generate both integrated and
        # no-host item-direct units. Effective host is no-host.
        units = _units("including_pass_weak", "P11")
        self.assertEqual(
            units.get("evaluative-stance|no-host -> ITEM-DIRECT"), 1)
        self.assertNotIn("evaluative-stance|integrated -> ITEM-DIRECT",
                         units)

    def test_no_categorical_p12_inherited_units(self):
        units = _units("including_pass_weak", "P12")
        self.assertNotIn("categorical-default -> CLASS-INHERITED", units)

    def test_verdicts_carry_effective_fields_and_model_attribution(self):
        doc = json.loads((BASE / "semantic-verdicts.json").read_text())
        self.assertIn("no human", doc["_note"].casefold())
        for key, rec in doc["verdicts"].items():
            self.assertIn("effective", rec, key)
            self.assertIn("canonical_proposition", rec, key)


if __name__ == "__main__":
    unittest.main()
